    private static int next(int n) {
        int s = 0;
        while (n > 0) { int d = n % 10; s += d * d; n /= 10; }
        return s;
    }

    private static int solve(int n, int row, int cols, int d1, int d2) {
        if (row == n) return 1;
        int count = 0;
        for (int c = 0; c < n; c++) {
            int bit = 1 << c, b1 = 1 << (row + c), b2 = 1 << (row - c + n - 1);
            if ((cols & bit) != 0 || (d1 & b1) != 0 || (d2 & b2) != 0) continue;
            count += solve(n, row + 1, cols | bit, d1 | b1, d2 | b2);
        }
        return count;
    }
